-- ─────────────────────────────────────────────────────────────
-- 13.7 — the staff documents vault
--
-- The table has existed since 0015 and has been used for exactly one thing:
-- the tax PDFs the app generates. There has never been a way to put anything
-- else in it, so a signed handbook acknowledgement, a copy of a CPR card and
-- a background-check result all live in somebody's email.
--
-- Three changes make it a vault rather than a drawer the code writes to.
--
-- The categories become data, like every other list in this system that
-- turned out to need a new entry six months later.
--
-- A person may put their own documents in. Admin-only upload made sense when
-- the only writer was the tax-form generator; it is wrong for "send us your
-- CPR card", which is a thing the person does. Deleting stays Admin's,
-- because a personnel file somebody can quietly empty is not a personnel file.
--
-- And opening one is recorded, for the same reason opening a tax form is:
-- these are personnel records, and who read them is a fair question.
-- ─────────────────────────────────────────────────────────────

create table if not exists public.staff_file_categories (
  key         text primary key,
  label       text not null,
  detail      text not null default '',
  -- Generated by the app rather than uploaded by a person. Offered nowhere,
  -- because nobody uploads their own W-9 — they sign it here.
  system_only boolean not null default false,
  sort_order  integer not null default 100,
  active      boolean not null default true
);

alter table public.staff_file_categories enable row level security;

drop policy if exists staff_file_categories_read on public.staff_file_categories;
drop policy if exists staff_file_categories_write on public.staff_file_categories;

create policy staff_file_categories_read on public.staff_file_categories
  for select to authenticated using (public.is_active_staff());
create policy staff_file_categories_write on public.staff_file_categories
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

