-- The check constraint becomes a foreign key. Every value already in the
-- table is in the catalogue above, which is why this can be done in place.
alter table public.staff_files drop constraint if exists staff_files_category_check;

do $$
begin
  if not exists (
    select 1 from pg_constraint
     where conrelid = 'public.staff_files'::regclass and conname = 'staff_files_category_fkey'
  ) then
    alter table public.staff_files
      add constraint staff_files_category_fkey
      foreign key (category) references public.staff_file_categories(key);
  end if;
end $$;

-- ─────────────────────────────────────────────────────────────
-- Who may put something in
--
-- Your own, or anybody's if you are Admin. The storage policy has to say the
-- same thing as the table policy or the row lands and the file does not.
-- ─────────────────────────────────────────────────────────────
drop policy if exists staff_files_insert on public.staff_files;
create policy staff_files_insert on public.staff_files
  for insert to authenticated
  with check (
    (public.is_admin() or staff_id = public.current_staff_id())
    and uploaded_by is not distinct from public.current_staff_id()
  );

drop policy if exists "zion write staff files" on storage.objects;
create policy "zion write staff files" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'staff-files' and public.is_active_staff());

-- Deleting stays Admin's. A personnel file somebody can quietly empty is not
-- a personnel file — and the tax PDFs live in this bucket too.

-- ─────────────────────────────────────────────────────────────
-- Opening one is recorded
--
-- Same shape as note_tax_form_access from 0054: the file is in storage, so
-- the database cannot be the door, but it can refuse to say the download is
-- allowed without writing down that it said so.
-- ─────────────────────────────────────────────────────────────
alter table public.access_log drop constraint if exists access_log_subject_check;
alter table public.access_log add constraint access_log_subject_check
  check (subject in (
    'Client restricted details',
    'Client intake',
    'Contractor tax number',
    'Signed tax form',
    'Staff document'
  ));

create or replace function public.note_staff_file_access(p_file_id uuid)
returns boolean language plpgsql security definer set search_path = public as $$
declare
  v_owner uuid;
  v_name  text;
  v_cat   text;
begin
  select staff_id, filename, category into v_owner, v_name, v_cat
    from public.staff_files where id = p_file_id;

  if v_owner is null then return false; end if;

  -- Yours, or anybody's if you are Admin — the same rule the table applies,
  -- restated here because this function decides whether a link is minted.
  if not (public.is_admin() or v_owner = public.current_staff_id()) then
    perform public.log_access('Staff document', null, v_owner, 'refused');
    return false;
  end if;

  -- Reading your own file is not an event worth recording. The question this
  -- log answers is who else has been through somebody's personnel file, and
  -- filling it with a person opening their own would bury that.
  if v_owner <> public.current_staff_id() then
    perform public.log_access('Staff document', null, v_owner,
                              'opened ' || v_cat || ': ' || v_name);
  end if;

  return true;
end;
$$;

revoke execute on function public.note_staff_file_access(uuid) from public;
grant execute on function public.note_staff_file_access(uuid) to authenticated;

